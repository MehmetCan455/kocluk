import type { ExamType } from '@/domain/types';
import type { CurriculumSeed, CurriculumSubjectSeed, CurriculumTopicSeed } from '@/db/seed';

/**
 * Curriculum version history:
 * - 2: first shipped MEB/YÖK YKS curriculum (Task 5).
 * Default app settings start at seedVersion 1, so version 2 triggers the
 * initial seed on a fresh database.
 */
const CURRICULUM_VERSION = 2;

interface SubjectDefinition {
  seedKey: string;
  exam: ExamType;
  name: string;
  slug: string;
  icon: string;
  topics: readonly string[];
}

const ASCII_CHARACTERS: Record<string, string> = {
  ç: 'c',
  Ç: 'c',
  ğ: 'g',
  Ğ: 'g',
  ı: 'i',
  İ: 'i',
  ö: 'o',
  Ö: 'o',
  ş: 's',
  Ş: 's',
  ü: 'u',
  Ü: 'u',
  â: 'a',
  Â: 'a',
  î: 'i',
  Î: 'i',
  û: 'u',
  Û: 'u',
};

/** Türkçe ünite adını kararlı, ASCII bir seed anahtarına çevirir. */
function topicSlug(name: string): string {
  return name
    .replace(/[çÇğĞıİöÖşŞüÜâÂîÎûÛ]/g, (character) => ASCII_CHARACTERS[character] ?? character)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function defineSubject(definition: SubjectDefinition, order: number): CurriculumSubjectSeed {
  const topics: CurriculumTopicSeed[] = definition.topics.map((name, index) => ({
    seedKey: `${definition.seedKey}-${topicSlug(name)}`,
    name,
    order: index + 1,
  }));

  return {
    seedKey: definition.seedKey,
    exam: definition.exam,
    name: definition.name,
    slug: definition.slug,
    icon: definition.icon,
    order,
    topics,
  };
}

